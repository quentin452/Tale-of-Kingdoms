
package mods.aginsun.kingdoms.util;

public class FakeBlock {
    public int blockID;
    public int metadata;
    public int posX;
    public int posY;
    public int posZ;

    public FakeBlock(int blockID, int metadata, int posX, int posY, int posZ) {
        this.blockID = blockID;
        this.metadata = metadata;
        this.posX = posX;
        this.posY = posY;
        this.posZ = posZ;
    }
}

